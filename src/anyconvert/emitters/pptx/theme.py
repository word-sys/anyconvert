"""PresentationML theme, master, and layout XML generators conforming to ISO/IEC 29500."""

from __future__ import annotations

from typing import List


def build_presentation_xml(slide_rids: List[str], width_emu: int, height_emu: int) -> bytes:
    """Generate ppt/presentation.xml content."""
    lines = [
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>',
        '<p:presentation xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main"',
        '                xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"',
        '                xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main">',
        '  <p:sldMasterIdLst>',
        '    <p:sldMasterId id="2147483648" r:id="rIdMaster1"/>',
        '  </p:sldMasterIdLst>',
        '  <p:sldIdLst>',
    ]

    for idx, rid in enumerate(slide_rids):
        sld_id = 256 + idx
        lines.append(f'    <p:sldId id="{sld_id}" r:id="{rid}"/>')

    lines.extend([
        '  </p:sldIdLst>',
        f'  <p:sldSz cx="{width_emu}" cy="{height_emu}" type="custom"/>',
        '  <p:notesSz cx="6858000" cy="9144000"/>',
        '</p:presentation>',
    ])
    return "\n".join(lines).encode("utf-8")


