"""PresentationML theme, master, and layout XML generators conforming to ISO/IEC 29500."""

from __future__ import annotations

from typing import List


def build_presentation_xml(
    slide_rids: List[str],
    width_emu: int,
    height_emu: int,
    sld_sz_type: str = "custom",
    notes_width_emu: int = 6858000,
    notes_height_emu: int = 9144000,
) -> bytes:
    """Generate ppt/presentation.xml content."""
    lines = [
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>',
        '<p:presentation xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main"',
        '                xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"',
        '                xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main">',
        '  <p:sldMasterIdLst>',
        '    <p:sldMasterId id="2147483648" r:id="rIdMaster1"/>',
        '  </p:sldMasterIdLst>',
        '  <p:sldIdLst>',
    ]

    for idx, rid in enumerate(slide_rids):
        sld_id = 256 + idx
        lines.append(f'    <p:sldId id="{sld_id}" r:id="{rid}"/>')

    lines.extend([
        '  </p:sldIdLst>',
        f'  <p:sldSz cx="{width_emu}" cy="{height_emu}" type="{sld_sz_type}"/>',
        f'  <p:notesSz cx="{notes_width_emu}" cy="{notes_height_emu}"/>',
        '  <p:defaultTextStyle>',
        '    <a:defPPr>',
        '      <a:defRPr lang="en-US"/>',
        '    </a:defPPr>',
        '    <a:lvl1pPr marL="0" algn="l" defTabSz="914400" rtl="0" eaLnBrk="1" latinLnBrk="0" hangingPunct="1">',
        '      <a:defRPr sz="1400" kern="1200">',
        '        <a:solidFill><a:schemeClr val="tx1"/></a:solidFill>',
        '        <a:latin typeface="+mn-lt"/>',
        '        <a:ea typeface="+mn-ea"/>',
        '        <a:cs typeface="+mn-cs"/>',
        '      </a:defRPr>',
        '    </a:lvl1pPr>',
        '  </p:defaultTextStyle>',
        '</p:presentation>',
    ])
    return "\n".join(lines).encode("utf-8")


